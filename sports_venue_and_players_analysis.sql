--Window Functions
--Rank venues by revenue
SELECT
    venue_name,
    SUM(final_amount) AS total_revenue,

    RANK() OVER (
        ORDER BY SUM(final_amount) DESC
    ) AS revenue_rank

FROM bookings
GROUP BY venue_name;
--Rank sports by revenue
SELECT
    sport,
    SUM(final_amount) AS total_revenue,

    RANK() OVER (
        ORDER BY SUM(final_amount) DESC
    ) AS revenue_rank

FROM bookings
GROUP BY sport;
--Rank users by number of bookings
SELECT
    user_id,
    COUNT(*) AS total_bookings,

    RANK() OVER (
        ORDER BY COUNT(*) DESC
    ) AS booking_rank

FROM bookings
GROUP BY user_id;

--ROW_NUMBER()
SELECT
    user_id,
    booking_id,
    booking_date,
    ROW_NUMBER() OVER (
        PARTITION BY user_id
        ORDER BY booking_date
    ) AS booking_number
FROM bookings;

--LAG()
SELECT
    user_id,
    booking_date,
    final_amount,
    LAG(final_amount) OVER (
        PARTITION BY user_id
        ORDER BY booking_date
    ) AS previous_booking_amount
FROM bookings;

--Running Revenue
SELECT
    booking_date,
    final_amount,

    SUM(final_amount) OVER (
        ORDER BY booking_date
    ) AS cumulative_revenue

FROM bookings
ORDER BY booking_date;

--Monthly Revenue + Previous Month Comparison
WITH monthly_revenue AS (
    SELECT
        DATE_TRUNC('month', booking_date) AS month,
        SUM(final_amount) AS revenue
    FROM bookings
    GROUP BY DATE_TRUNC('month', booking_date)
)

SELECT
    month,
    revenue,

    LAG(revenue) OVER (
        ORDER BY month
    ) AS previous_month_revenue

FROM monthly_revenue
ORDER BY month;

--PARTITION BY
SELECT
    user_id,
    booking_date,
    final_amount,

    AVG(final_amount) OVER (
        PARTITION BY user_id
    ) AS user_average_booking_value
FROM bookings;

--Conditional Aggregation
SELECT
    sport,

    COUNT(*) AS total_bookings,

    SUM(
        CASE
            WHEN is_cancelled = 1 THEN 1
            ELSE 0
        END
    ) AS cancelled_bookings,
    SUM(
        CASE
            WHEN is_cancelled = 0 THEN 1
            ELSE 0
        END
    ) AS completed_bookings
FROM bookings
GROUP BY sport;




