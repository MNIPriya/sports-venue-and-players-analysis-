CREATE TABLE bookings (
    booking_id VARCHAR(50),
    user_id VARCHAR(50),
    venue_id VARCHAR(50),
    booking_date DATE,
    booking_time TIME,
    sport VARCHAR(50),
    city VARCHAR(100),
    area VARCHAR(100),
    venue_name VARCHAR(150),
    court_type VARCHAR(100),
    duration_hours INT,
    players_count INT,
    booking_amount INT,
    discount INT,
    final_amount INT,
    payment_method VARCHAR(50),
    booking_status VARCHAR(50),
    cancellation_reason VARCHAR(150),
    booking_source VARCHAR(50),
    booking_lead_days INT,
    rating NUMERIC,
    booking_hour INT,
    day_type VARCHAR(20),
    month VARCHAR(20),
    weekday VARCHAR(20),
    is_cancelled INT
);
